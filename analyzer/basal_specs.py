def gddr_rule(title, desc=""):
    for text in (nrm(title), nrm(desc)):
        found = set(re.findall(r"\bg?ddr\s?([3456])\s?(x)?\b", text))
        found = {("gddr6x" if x else f"gddr{n}") if n in "56" else "ddr4_ddr3" for n, x in found}
        if found:
            return found.pop() if len(found) == 1 else "sprzeczne"
    return UNKNOWN


