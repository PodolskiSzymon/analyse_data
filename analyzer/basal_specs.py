    return (rf"(?:(?<![0-9]){n}(?:\.|th|st|nd|rd|-?ej|-?a)?{S}(?:gen\w*|generac\w*|gener\w*)|"
            rf"(?:gen\w*|generac\w*){S}{n}(?![0-9]|[.,]\d))")


